/** SVG path (unit squares) for a string; 6 columns per character including spacing. */
export function textPath(text: string): string {
  let d = '';
  [...text.toUpperCase()].forEach((ch, i) => {
    (GLYPHS[ch] ?? GLYPHS['?']!).forEach((bits, y) => {
      for (let x = 0; x < 5; x++) if (bits & (16 >> x)) d += `M${i * 6 + x} ${y}h1v1h-1z`;
    });
  });
  return d;
}
